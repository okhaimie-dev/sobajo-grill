import type { Metadata } from "next";
import { SITE, absoluteUrl } from "./site";

export const OG_IMAGE = {
  url: absoluteUrl("/og.png"), // generated by app/og.png/route.tsx
  width: 1200,
  height: 630,
  alt: "Sobajo Grill — Fire. Flavor. Friendship. Baltimore suya & African barbecue",
};

/**
 * Full per-page metadata. Next merges `openGraph`/`twitter` shallowly, so
 * every page restates them here rather than inheriting from the layout.
 */
export function pageMetadata({
  title,
  description,
  path,
}: {
  /** Omit on the home page to use the default brand title. */
  title?: string;
  description: string;
  /** Route with trailing slash, e.g. "/menu/". */
  path: string;
}): Metadata {
  const url = absoluteUrl(path);
  const fullTitle = title ? `${title} | ${SITE.name}` : SITE.title;
  return {
    title: title ?? { absolute: SITE.title },
    description,
    alternates: { canonical: url },
    openGraph: {
      type: "website",
      locale: "en_US",
      url,
      siteName: SITE.name,
      title: fullTitle,
      description,
      images: [OG_IMAGE],
    },
    twitter: { card: "summary_large_image", title: fullTitle, description, images: [OG_IMAGE] },
  };
}
